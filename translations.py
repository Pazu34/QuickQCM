"""Internationalization (i18n) for the QCM Scanner interface.

All user-facing text in qcm_app.py goes through tr(key, **kwargs) rather
than being hardcoded in French. Backend error messages raised by the
already-tested modules (generate_sheet_modular, detect_modular,
roster_match) are NOT translated here -- only the surrounding text
qcm_app.py itself writes is (see e.g. err_generate_failed: the label
"Detail:" is translated, the exception text it wraps stays as raised).

The selected language is persisted via app_config settings ("language"
key) and can be changed live from the Préférences/Preferences tab --
switching it triggers a full rebuild of the notebook tabs so every label
updates immediately, no restart needed.
"""
import app_config

LANGUAGES = {"fr": "Français", "en": "English", "de": "Deutsch", "es": "Español"}

_current_language = "fr"


def get_language():
    return _current_language


def set_language(lang):
    global _current_language
    if lang in LANGUAGES:
        _current_language = lang


def load_language_from_settings():
    global _current_language
    s = app_config.load_settings()
    lang = s.get("language", "fr")
    _current_language = lang if lang in LANGUAGES else "fr"


def tr(key, **kwargs):
    """Looks up `key` in the current language's dictionary, falling back
    to French (the original source language) then to the key itself if
    truly missing. Formats with **kwargs when given (str.format style)."""
    template = TRANSLATIONS.get(_current_language, {}).get(key)
    if template is None:
        template = TRANSLATIONS["fr"].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template


